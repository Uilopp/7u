#!/usr/bin/env node
// Deterministic vector export. Requires sharp (or SEVENU_SHARP_MODULE pointing
// to its installed directory). The SVG is the only editable artwork source.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const sharp = require(process.env.SEVENU_SHARP_MODULE || 'sharp');

const root = path.resolve(__dirname, '..');
const app = path.join(root, 'app');
const branding = path.join(app, 'assets', 'branding');
const res = path.join(app, 'android', 'app', 'src', 'main', 'res');
const svg = fs.readFileSync(path.join(branding, '7u-mark.svg'), 'utf8');
const background = /id="background"[^>]*fill="(#[A-Fa-f0-9]{6})"/.exec(svg)?.[1];
const foreground = /id="wordmark"[^>]*stroke="(#[A-Fa-f0-9]{6})"/.exec(svg)?.[1];
const width = Number(/stroke-width="([\d.]+)"/.exec(svg)?.[1]);
const paths = [...svg.matchAll(/<path d="([^"]+)"/g)].map((match) => match[1]);
assert(background && foreground && width && paths.length === 2, 'Invalid brand SVG');
assert(!/<text\b|<image\b|href=/.test(svg), 'The mark must be paths without external assets');

function write(relative, contents) {
  const destination = path.join(app, relative);
  fs.mkdirSync(path.dirname(destination), { recursive: true });
  fs.writeFileSync(destination, contents);
}

function vector(color) {
  return `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by tools/build_android_icons.cjs from assets/branding/7u-mark.svg. -->
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp" android:height="108dp"
    android:viewportWidth="108" android:viewportHeight="108">
${paths.map((d) => `    <path android:pathData="${d}" android:fillColor="@android:color/transparent"
        android:strokeColor="${color}" android:strokeWidth="${width}"
        android:strokeLineCap="round" android:strokeLineJoin="round" />`).join('\n')}
</vector>
`;
}

function dartPath(d) {
  const tokens = d.match(/[A-Z]|-?\d+(?:\.\d+)?/g);
  let i = 0;
  let x = 0;
  let y = 0;
  const calls = [];
  while (i < tokens.length) {
    const command = tokens[i++];
    const number = () => Number(tokens[i++]);
    if (command === 'M' || command === 'L') {
      x = number(); y = number();
      calls.push(`..${command === 'M' ? 'moveTo' : 'lineTo'}(${x}, ${y})`);
    } else if (command === 'H') {
      x = number(); calls.push(`..lineTo(${x}, ${y})`);
    } else if (command === 'V') {
      y = number(); calls.push(`..lineTo(${x}, ${y})`);
    } else if (command === 'C') {
      const values = Array.from({ length: 6 }, number);
      [x, y] = values.slice(-2);
      calls.push(`..cubicTo(${values.join(', ')})`);
    } else {
      throw new Error(`Unsupported SVG command ${command}; expand it in the source first.`);
    }
  }
  return `Path()\n        ${calls.join('\n        ')}`;
}

async function main() {
  // The whole monogram must survive even a tight circular adaptive mask.
  const isolated = `<svg xmlns="http://www.w3.org/2000/svg" width="108" height="108" viewBox="0 0 108 108"><g fill="none" stroke="white" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round">${paths.map((d) => `<path d="${d}"/>`).join('')}</g></svg>`;
  const pixels = await sharp(Buffer.from(isolated)).ensureAlpha().raw().toBuffer();
  let visiblePixels = 0;
  for (let y = 0; y < 108; y++) {
    for (let x = 0; x < 108; x++) {
      if (pixels[(y * 108 + x) * 4 + 3] > 20) {
        visiblePixels++;
        assert(Math.hypot(x + .5 - 54, y + .5 - 54) <= 33, 'Wordmark escapes the adaptive icon safe circle');
      }
    }
  }
  assert(visiblePixels > 200, 'Wordmark is not visible');
  write('android/app/src/main/res/drawable/ic_launcher_foreground.xml', vector(foreground));
  write('android/app/src/main/res/drawable/ic_launcher_monochrome.xml', vector('#FFFFFF'));
  write('android/app/src/main/res/values/icon_colors.xml', `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated from assets/branding/7u-mark.svg. -->
<resources><color name="ic_launcher_background">${background}</color></resources>
`);
  for (const [qualifier, monochrome] of [['v26', false], ['v33', true]]) {
    write(`android/app/src/main/res/mipmap-anydpi-${qualifier}/ic_launcher.xml`, `<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_background" />
    <foreground android:drawable="@drawable/ic_launcher_foreground" />
${monochrome ? '    <monochrome android:drawable="@drawable/ic_launcher_monochrome" />\n' : ''}</adaptive-icon>
`);
  }
  for (const [density, size] of Object.entries({ mdpi: 48, hdpi: 72, xhdpi: 96, xxhdpi: 144, xxxhdpi: 192 })) {
    const output = path.join(res, `mipmap-${density}`, 'ic_launcher.png');
    fs.mkdirSync(path.dirname(output), { recursive: true });
    await sharp(Buffer.from(svg)).resize(size, size).png().toFile(output);
    const image = await sharp(output).metadata();
    assert.equal(image.width, size);
    assert.equal(image.height, size);
    assert.equal(image.hasAlpha, true);
  }
  await sharp(Buffer.from(svg)).resize(512, 512).png().toFile(path.join(branding, '7u-icon.png'));
  const mark = paths.map((d) => `<path d="${d}"/>`).join('');
  const sample = (x, y, size, radius, bg, fg) => `<g transform="translate(${x} ${y}) scale(${size / 108})">
    <rect width="108" height="108" rx="${radius}" fill="${bg}"/>
    <g fill="none" stroke="${fg}" stroke-width="${width}" stroke-linecap="round" stroke-linejoin="round">${mark}</g></g>`;
  const preview = `<svg xmlns="http://www.w3.org/2000/svg" width="1040" height="660" viewBox="0 0 1040 660">
    <rect width="1040" height="660" fill="#E9EDF2"/>
    ${sample(70, 105, 360, 26, background, foreground)}
    ${sample(555, 130, 220, 54, background, foreground)}
    ${sample(815, 180, 120, 27, '#DCE5DD', background)}
    ${sample(582, 425, 48, 24, background, foreground)}
    ${sample(674, 413, 72, 24, background, foreground)}
    ${sample(790, 401, 96, 24, background, foreground)}
  </svg>`;
  await sharp(Buffer.from(preview)).png().toFile(path.join(branding, '7u-icon-preview.png'));
  write('lib/widgets/seven_u_mark.dart', `// GENERATED from assets/branding/7u-mark.svg by tools/build_android_icons.cjs.
// Edit the SVG and regenerate; this artwork does not depend on a device font.
import 'package:flutter/material.dart';

const sevenUInk = Color(0xff${background.slice(1)});
const sevenUIvory = Color(0xff${foreground.slice(1)});

class SevenUMark extends StatelessWidget {
  final Color color;
  const SevenUMark({super.key, this.color = sevenUIvory});

  @override
  Widget build(BuildContext context) => CustomPaint(painter: _MarkPainter(color));
}

class _MarkPainter extends CustomPainter {
  final Color color;
  const _MarkPainter(this.color);

  @override
  void paint(Canvas canvas, Size size) {
    canvas.save();
    canvas.scale(size.width / 108, size.height / 108);
    final paint = Paint()
      ..color = color
      ..style = PaintingStyle.stroke
      ..strokeWidth = ${width}
      ..strokeCap = StrokeCap.round
      ..strokeJoin = StrokeJoin.round;
${paths.map((d, i) => `    final path${i} = ${dartPath(d)};\n    canvas.drawPath(path${i}, paint);`).join('\n')}
    canvas.restore();
  }

  @override
  bool shouldRepaint(_MarkPainter oldDelegate) => oldDelegate.color != color;
}
`);
  console.log('Validated paths, adaptive safe circle, PNG dimensions/alpha. Generated Android icons, Flutter mark and preview.');
}

main().catch((error) => { console.error(error.message); process.exitCode = 1; });
